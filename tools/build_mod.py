"""Builds the extension folders under dist/ from config/variants.json.

Each variant becomes
  dist/<id>/content.xml                  mod metadata (Egosoft format, bilingual texts)
  dist/<id>/libraries/sound_library.xml  XML diff: redirects Boso Ta's six sound entries to the mod's audio folder
                                         and patches attributes (noocclusion, is3d)
The audio itself is not part of dist/; tools/install_mod.py adds it from build/audio/<audio_variant>/.

Usage: python -I tools/build_mod.py [--only <variant key>]
"""
import argparse
import datetime
import json
import sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent.parent
CFG_PATH = ROOT / "config" / "variants.json"
DIST = ROOT / "dist"


def build_diff(v, cfg):
    """Redirect every Boso Ta entry to extensions\\<id>\\voice\\10201\\normal (the engine takes this path literally,
    without a language suffix – proven in diagnostic v6) and apply the configured attribute operations."""
    target = f"extensions\\{v['id']}\\voice\\10201\\normal"
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<diff>",
           f"  <!-- generated by tools/build_mod.py – variant {v['id']} (audio: {v['audio_variant']}) -->"]
    for sound_id in cfg["boso_ta_ids"]:
        out.append(f"  <replace sel=\"/soundlibrary/sound[@id='{sound_id}']/sample\">")
        out.append(f'    <sample start="{target}"/>')
        out.append("  </replace>")
    # {"op": "add", "ids": [...], "attr": "noocclusion", "value": "true"}  creates an attribute
    # {"op": "replace", "ids": [...], "attr": "is3d", "value": "0"}        changes an existing one
    for item in v.get("sound_attr_ops", []):
        for sound_id in item["ids"]:
            sel = f"/soundlibrary/sound[@id='{sound_id}']"
            if item["op"] == "add":
                out.append(f'  <add sel="{sel}" type="@{item["attr"]}">{item["value"]}</add>')
            else:
                out.append(f'  <replace sel="{sel}/@{item["attr"]}">{item["value"]}</replace>')
    out.append("</diff>")
    return "\n".join(out) + "\n"


def build_content(v, cfg):
    q = quoteattr  # XML-safe attribute values (&, <, > and quotes are escaped)
    today = datetime.date.today().isoformat()
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f"<content id={q(v['id'])} name={q(v['name_en'])} description={q(v['desc_en'])} "
            f"author={q(cfg['author'])} version={q(v.get('version', cfg['version']))} date={q(today)} enabled=\"1\" save=\"0\">\n"
            f"  <text language=\"44\" name={q(v['name_en'])} description={q(v['desc_en'])}/>\n"
            f"  <text language=\"49\" name={q(v['name_de'])} description={q(v['desc_de'])}/>\n"
            "</content>\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", help="build only this variant key")
    args = ap.parse_args()
    cfg = json.loads(CFG_PATH.read_text(encoding="utf-8"))
    for key, v in cfg["variants"].items():
        if args.only and key != args.only:
            continue
        target = DIST / v["id"]
        (target / "libraries").mkdir(parents=True, exist_ok=True)   # overwrite in place (OneDrive locks fresh folders)
        (target / "content.xml").write_text(build_content(v, cfg), encoding="utf-8")
        (target / "libraries" / "sound_library.xml").write_text(build_diff(v, cfg), encoding="utf-8")
        audio = ROOT / "build" / "audio" / v["audio_variant"]
        n_audio = len(list(audio.glob("*.ogg"))) if audio.is_dir() else 0
        hint = "" if n_audio else "  NOTE: no audio yet – run tools/process_audio.py"
        print(f"built: {target.relative_to(ROOT)}  ({len(cfg['boso_ta_ids'])} sound ids, {n_audio} ogg in build/audio/{v['audio_variant']}){hint}")


if __name__ == "__main__":
    main()
